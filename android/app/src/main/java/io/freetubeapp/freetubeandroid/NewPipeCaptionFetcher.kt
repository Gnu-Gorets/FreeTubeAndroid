package io.freetubeapp.freetubeandroid

import android.net.Uri
import org.schabi.newpipe.extractor.NewPipe
import org.schabi.newpipe.extractor.MediaFormat
import java.io.ByteArrayInputStream
import java.io.IOException

internal object NewPipeCaptionFetcher {
    fun fetch(url: String): CaptionTransport.Response? {
        if (!CaptionTransport.matches("GET", url)) return null
        val request = Uri.parse(url)
        if (request.getQueryParameter("fmt") != "ttml") return null
        val videoId = request.getQueryParameter("v")?.takeIf { it.matches(Regex("[A-Za-z0-9_-]{11}")) }
            ?: throw IOException("Invalid YouTube video ID")
        val language = request.getQueryParameter("lang") ?: throw IOException("Missing caption language")
        val kind = request.getQueryParameter("kind")
        if (request.getQueryParameter("tlang") != null) return null

        val downloader = NewPipeCaptionDownloader.get()
        val videoUrl = "https://www.youtube.com/watch?v=$videoId"
        val extractor = NewPipe.getServiceByUrl(videoUrl).getStreamExtractor(videoUrl)
        extractor.fetchPage()
        val subtitle = extractor.getSubtitles(MediaFormat.TTML).firstOrNull {
            it.languageTag.equals(language, ignoreCase = true) &&
                (kind != "asr" || it.isAutoGenerated) &&
                (kind == "asr" || !it.isAutoGenerated)
        } ?: throw IOException("NewPipe did not return matching caption track")

        val response = downloader.get(
            subtitle.content,
            mapOf(
                "Referer" to listOf("https://www.youtube.com/sw.js"),
                "Sec-Fetch-Site" to listOf("same-origin"),
                "Sec-Fetch-Mode" to listOf("same-origin"),
                "Accept" to listOf("application/ttml+xml,*/*")
            )
        )
        val bytes = response.responseBody().toByteArray(Charsets.UTF_8)
        val headers = buildMap {
            put("Content-Type", response.getHeader("Content-Type") ?: "application/ttml+xml; charset=utf-8")
            response.getHeader("Retry-After")?.let { put("Retry-After", it) }
            put("Access-Control-Allow-Origin", "*")
        }
        return CaptionTransport.Response(
            response.responseCode(),
            response.responseMessage().ifBlank { "HTTP response" },
            headers,
            ByteArrayInputStream(bytes)
        )
    }
}
